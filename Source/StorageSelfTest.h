/**
    8.286：**プロジェクトの置き場所**を、窓を出さずに確かめる（Phase 279）。

    ```
    "Manta Studio.exe" --storage-selftest
    ```

    ### なぜ機械に数えさせるのか

    ここが決めるのは「**本人の作ったものがどこへ落ちるか**」です。
    間違えても**その場では何も起きません**——保存も録音も成功し、
    ファイルはどこかに出来ています。気づくのは

    - 曲のフォルダを別のドライブへ移したら、**音が出なくなった**
    - 「名前を付けて保存」したのに、**フォルダが作られていない**
    - 上書き保存の控え（`.bak`）が、**どこにも無い**

    というときで、そこから遡るのは大変です。

    ### 見るもの

    | | |
    |---|---|
    | フォルダの作り分け | 根の直下なら`<根>/<名前>/<名前>.em1`、それ以外は**そのまま** |
    | 中の置き場所 | `Backup`／`Rec`／`Stems`／`Mixdown`。未保存なら**空を返す** |
    | 保存の控え | 2回目の保存で`Backup/<名前>.em1.bak`ができる |

    **本人の設定は触りません。** 根は引数で渡せるようにしてあり
    （`makeProjectFileInOwnFolder()`の2引数版）、
    書き込みは一時フォルダの中だけで終わります。

    **問題の数を終了コードで返します**（0なら合格）。
*/
namespace StorageSelfTest
{
    /** コマンドラインに`--storage-selftest`があれば走らせて、trueを返す。 */
    bool runIfRequested (const juce::String& commandLine);
}
