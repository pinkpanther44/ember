#pragma once

#include <juce_core/juce_core.h>

//==============================================================================
/**
    8.163：**表示の言語**（Phase 201／本人の要望。仕様書6章）。

    ### 3つの出し方

    | | ラベル（ボタン名・メニュー・見出し） | 説明（ツールチップ・案内文・状態表示） |
    |---|---|---|
    | `japanese` | 日本語 | 日本語 |
    | `english` | 英語 | 英語 |
    | `englishWithJapaneseHelp` | 英語 | **日本語** |

    3つめは本人の指定です——**用語は英語のほうが他のDAWや解説と揃う**一方、
    「これは何なのか」の説明は母語のほうが速い、という組み合わせです。

    ### 日本語そのものが見出し（キー）です

    `tr("保存")`のような**別の見出しを付けていません。**
    `Utf8.h`の`utf8()`——日本語リテラルを`juce::String`にする、
    **画面に出る日本語がもれなく通っている1箇所**——をそのまま通り道にしています。

    そのおかげで：

    - **呼び出し側を1行も変えずに済みます**（866箇所ありました）
    - **見出しの付け忘れが起こりません。** 別の見出し方式だと、
      新しい文字列を足すたびに「見出しを付ける」作業が要り、
      忘れたぶんだけ日本語のまま残ります（8.2の「入口が2つ」と同じ穴）
    - **訳が無いときは日本語が出ます。** 表に載せ忘れても、
      画面が空になったり見出しの文字列が出たりはしません

    引き換えに、**日本語を書き換えたら表の見出しも書き換える**必要があります。
    `Tools/CheckTranslations`が「表にあるのにソースに無い」見出しを
    洗い出すので、そちらで拾えます。

    ### 速さ

    `utf8()`は`paint()`の中からも呼ばれます。**日本語のときは何も引きません**
    （`mode`を見て即座に返す）ので、既定の設定では今までと同じ速さです。
    英語のときだけ`std::string_view`で引きます——
    **`juce::String`を作らずに引ける**ので、確保も走りません。

    ### 切り替えは次の起動から

    ラベルの多くは**コンポーネントの構築時に1度だけ**入ります。
    その場で差し替えるには全部を作り直すことになるので、
    **設定を書いて、次の起動から効かせます**（テーマと同じ扱い。設計書2.5）。
*/
namespace Localise
{
    enum class Mode
    {
        japanese = 0,               ///< 既定。Phase 200までと同じ
        english = 1,                ///< 全部英語
        englishWithJapaneseHelp = 2 ///< ラベルは英語、説明は日本語
    };

    /** いまの言語。**アプリ設定から読んだ値**で、起動時に1度だけ決まる。 */
    Mode getMode();

    /** 言語を設定へ書く。**その場では画面は変わりません**（次の起動から）。 */
    void setMode (Mode newMode);

    /** 設定から読み込む。**`AppSettings`を読める状態になってから、起動時に1度呼ぶこと。** */
    void loadFromSettings();

    /** 言語の名前（設定画面のコンボボックスに出すもの）。 */
    juce::String getModeName (Mode mode);

    /** 日本語のリテラルを、いまの言語へ直して返す。

        **`utf8()`から呼ばれます。** 直接呼ばないこと——
        通り道が2つになると、片方だけ訳される文字列ができます（8.2）。 */
    juce::String translate (const char* japaneseUtf8);

    //==========================================================================
    /** 訳の表の1行。**リテラルを指すだけ**なので、確保も複写も走らない。 */
    struct Entry
    {
        const char* japanese;  ///< ソースに書いてある日本語（そのまま。見出しでもある）
        const char* english;   ///< 英語
        bool isHelp;           ///< 説明文なら真（3つめの言語で日本語のまま出る）
    };

    /** 表そのもの。`LocaliseTable.cpp`が持っている。 */
    const Entry* getTable (int& numEntriesOut);
}
