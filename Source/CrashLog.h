/**
    8.316：**落ちたときに、落ちた場所を残す**（Phase 309／本人の報告を追うため）。

    ### なぜ要るのか

    「Audioの入力をnoneにすると落ちる」という報告を追ったとき、
    **手元には番地しかありませんでした**——Windowsのイベントログが出す
    「フォールト オフセット」1つです。**呼び出しの道筋がありません。**

    番地1つでも、`.map`を持っていれば関数までは辿れます（実際そうしました）。
    ですが**そこへ至った道が分からない**ので、「誰がその状態にしたのか」は
    推測で埋めることになります。**推測で直すと、直った証拠も作れません。**

    ### やっていること

    **ntdllの巻き戻しだけ**を使います（`RtlLookupFunctionEntry`＋`RtlVirtualUnwind`）。
    **シンボルは要りません**——出すのは**モジュール名＋その中での番地（RVA）**だけで、
    人のほうで`.map`と突き合わせます。

    `dbghelp`を持ち込めば名前まで出せますが、**配るものに重いものを足さない**ため、
    ここでは番地までにしています。番地が残っていれば、あとはいつでも引けます。

    ### 置き場所

    `%APPDATA%/Ember/crash-YYYYMMDD-HHMMSS.log`（設定と同じ場所）。
    **プロジェクトの隣には書きません**——落ちた拍子に作業フォルダを汚さないため。

    ### 注意

    **落ちたあとの処理では、何も当てにしないこと。** メモリが壊れている前提なので、
    ここでは`juce::File`と`juce::String`しか使っていません（どちらもメモリ確保はしますが、
    使えないほど壊れていれば、どのみち何も残せません）。
*/
namespace CrashLog
{
    /** 起動時に1回だけ呼ぶ。Windows以外では何もしない。 */
    void install();

    /** 残っているログの数。0なら「前回は落ちていない」。 */
    int getNumStoredReports();

    /** ログの置き場所（無ければ作らない）。 */
    juce::File getReportFolder();

    /** `--crash-selftest`なら、**わざと落ちて**ログを1つ残す。

        **仕掛けそのものを確かめるためのものです。** 落ちたときにしか働かない道具は、
        **本番で初めて動かすことになりがち**で、そこで書けなかったら何も残りません。

        戻ってきません（プロセスが終わります）。頼まれていなければ`false`を返します。 */
    bool runSelfTestIfRequested (const juce::String& commandLine);
}
