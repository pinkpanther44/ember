/**
    8.325：**MIDIの時間範囲**を、窓を出さずに確かめる（Phase 314／HANDOVER 9.2の①）。

    ```
    "Manta Studio.exe" --timerange-selftest
    ```

    ### なぜ要るのか

    範囲は**押した場所で振る舞いが分かれます**（空き＝引き始める／塊＝選ぶ／
    Ctrl＋塊＝足す／範囲の中＝掴む）。関数を直に呼ぶと、その振り分けを通りません。
    ここでは**マウスの出来事を座標で作って**、画面で押すのと同じ入口から通します。

    ### 見るもの

    **段違いの塊**（トラックAは1小節目、トラックBは5小節目）を選んだとき、
    **あいだにある別の塊が巻き込まれないこと**——削除・移動・トランスポーズ・
    切り取りのどれでも。あわせて：

    | | |
    |---|---|
    | Undo | **1回で全部戻る**こと（トラックごとに区切りが入ると、本数ぶん押すことになる） |
    | 切り取り | 選んだのはMIDIトラックだけなので、**マーカーとコード区間は残る**こと |
    | 枠で囲う | 囲った行は**同じ窓**のまま（前からの振る舞い） |
    | 1本だけ | 縦に動かすと別のトラックへ移る（前からの振る舞い） |
    | 8.326：同じトラックに2つ | **あいだを入れずに**窓が2つになること。動かすと**二度動かない**こと（1つ目の行き先が2つ目の窓のとき）。重なる窓は1つにまとまること |

    **問題の数を終了コードで返します**（0なら合格）。
*/
namespace TimeRangeSelfTest
{
    /** コマンドラインに`--timerange-selftest`があれば走らせて、trueを返す。 */
    bool runIfRequested (const juce::String& commandLine);
}
