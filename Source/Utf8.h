/**
    日本語などの非ASCII文字を含むリテラルを、juce::Stringへ安全に変換するヘルパー。

    juce::Stringの`const char*`版コンストラクタは7bit ASCII専用の解釈をするため、
    UTF-8のマルチバイト文字（日本語等）を含む文字列リテラルを「Stringへの変換が
    必要な引数位置」に直接渡すと、`jassert`で実行が止まってしまう
    （実際に発生・特定済み：juce_String.cpp内のCharPointer_ASCII::isValidStringチェック）。

    日本語リテラルをコンストラクタ引数・関数引数として直接渡す必要がある箇所
    （FileChooserのタイトル、Label::setTextへの直接指定等）では、
    必ずこの関数を経由すること。`text << "日本語"`のような連結記法は
    別の安全な経路を通るため対象外（このプロジェクトでの動作確認済み）。
*/
/*
    8.163：**ここが言語の通り道になりました**（Phase 201／本人の要望）。

    画面に出る日本語は**もれなくここを通ります**（866箇所）。
    通り道が1つしかないので、**呼び出し側を1行も変えずに**言語を切り替えられます
    ——そして**新しく足した日本語も、書いた時点で通り道に乗ります**
    （見出しを付け忘れて日本語のまま残る、が起こらない。8.2）。

    表に無い文字列は日本語のまま出ます。詳しくは`Localise.h`。
*/
inline juce::String utf8 (const char* text)
{
    return Localise::translate (text);
}
