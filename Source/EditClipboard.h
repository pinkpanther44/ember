/**
    仕様書6.2：カット／コピー／貼り付けの入れ物（Phase 71／8.29の表）。

    **対象ごとに別の入れ物を作らないこと。** ノート・CCイベント・クリップ・
    オートメーションの点は、どれも「ValueTreeの複製＋時刻」でしかありません。
    種別ごとにコピー機能を書くと、貼り付け位置の決め方（スナップ・相対位置）が
    4通りに散らばります（8.14のスナップと同じで、1箇所に集める）。

    **アプリ全体で1つ**です（`AppSettings`と同じく名前空間の関数）。
    OSのクリップボードとは別物で、アプリ内でだけやり取りします。

    使い方：
    - コピーする側は`set()`へ**複製したValueTree**を渡す（元をそのまま渡さないこと。
      元が消えたり動いたりすると、貼り付ける中身まで変わってしまう）
    - 貼り付ける側は`getKind()`で中身を確かめてから`getItems()`を読む
    - 位置は**`referenceTime`からの差**で持つ。貼り付け先の時刻に足せば、
      複数のものを選んだときの間隔がそのまま保たれる
*/
namespace EditClipboard
{
    /** 何が入っているか。**種別が合わないものは貼り付けない**（ノートをアレンジ画面へ、等）。 */
    enum class Kind
    {
        none,

        /** 8.95：**MIDIの中身**（`<NOTE>`と`<CC>`が混ざって入ります。Phase 135）。

            Phase 134まではノートだけでした。アレンジ画面で時間範囲をコピーすると
            **CCも一緒に運びたい**（ドラッグでの複製はそうなっている。8.92）ので、
            1つの入れ物に両方を入れています。

            **読む側は`hasType()`で振り分けること。** 種別を見ずに
            `IDs::notePitch`を読むと、CCから音程0のノートができます。 */
        notes,

        ccEvents,           // CCレーンの点だけ（ピアノロールのレーンからのコピー）
        clips,              // アレンジ画面のクリップ（<AUDIOCLIP>／<MIDICLIP>）
        automationPoints,   // オートメーションの点（<POINT>）

        /** 8.124：**マーカーで選んだ区間まるごと**（Phase 160／改善案5）。

            `<NOTE>`・`<CC>`・`<AUDIOCLIP>`が混ざって入ります。
            **`rowOffset`にはトラックの番号をそのまま入れます**（先頭からのずれではない）。

            区間の移動が上下を跨がない決まりなので（本人の指定）、
            貼り付けも**同じ番号のトラックへ戻す**のが素直です。
            番号が無くなっていたら、そのトラックのぶんは捨てます。

            **`clips`と分けてある理由**：`clips`は「選んだクリップ」で、
            貼り付け先は選択中のトラック1本です。こちらは
            **複数のトラックへ同時に戻る**ので、振り分け方が別ものになります。 */
        trackRange
    };

    /** 中身1つぶん。 */
    struct Item
    {
        juce::ValueTree state;

        /** 先頭のものからの「行」のずれ（クリップならトラック、CCならレーン）。

            **ノートには使いません**（音程はValueTreeの中に入っているため）。
            複数の行にまたがってコピーしたときに、貼り付け先でも同じ形を保つために持つ。 */
        int rowOffset = 0;

        /** `referenceTime`からの時刻のずれ（秒）。

            **オーディオクリップはこちらを使います**（伸び縮みしないので、
            貼り付け先のテンポで間隔が変わってはいけない。8.139）。 */
        double timeOffset = 0.0;

        /** 8.139：`referenceTime`からのずれを**拍で**（Phase 177／8.105の宿題3）。

            ### なぜ2つ持つのか

            **中身によって「間隔の意味」が違うからです。**

            | 中身 | 使うほう | なぜ |
            |---|---|---|
            | ノート・CC・コード区間・マーカー・オートメーション点 | **`beatOffset`** | 拍で保存されている。**貼り付け先のテンポで音楽的な間隔が保たれる** |
            | オーディオクリップ | `timeOffset` | 伸び縮みできない。秒の間隔が変わると音が重なる |

            Phase 176でノートの**長さ**だけを拍で運ぶようにしたので、
            **位置だけ秒のまま**という食い違いが残っていました（8.138の宿題）。
            ここで揃えます。

            **テンポが一定なら、どちらを使っても同じ値になります。** */
        double beatOffset = 0.0;
    };

    /** 中身を差し替える。**渡すのは複製したValueTree**。 */
    void set (Kind kind, juce::Array<Item> items);

    Kind getKind();
    bool isEmpty();

    const juce::Array<Item>& getItems();

    /** 中身を捨てる（プロジェクトを閉じたときなど）。 */
    void clear();
}
