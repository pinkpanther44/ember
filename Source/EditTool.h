/**
    仕様書6.2：マウスの役割（Studio Oneのツールに相当）。Phase 51で新設、Phase 52で共有化。

    **アレンジ画面（`TimelineComponent`）とピアノロール（`PianoRollComponent`）が
    同じものを使う。** Phase 51ではアレンジ画面の中だけで定義していたが、
    ピアノロールにも同じツールを効かせるにあたって、
    どちらからも見える場所へ出した。

    ツールの「いまの値」を持っているのは`MainComponent`で、
    切り替えるとどちらの画面へも同じ値が流れる（片方だけ古くなる状態を作らないため）。

    **Phase 69で`range`（範囲選択）を`arrow`へ畳んだ**（8.29の表）。
    矢印ツールで**空いている場所をドラッグすれば範囲選択**になるので、
    「選ぶために持ち替える」必要が無くなった。掴んだ時点では区別できないため、
    クリックとドラッグの振り分けは`mouseUp`で行う（8.10と同じ形）。

    **並びはショートカットの1・2・4・5と対**（3はrangeが使っていた番号で、いまは空き。
    Phase 83で足した消しゴムは、**空いている3ではなく5**にしてある——
    環境設定に残っている古い割り当てと取り合いにならないようにするため）。
    **既定キーを詰め直していない**のは、環境設定に保存済みの割り当てと
    食い違わせないため（8.6）。増やすときは末尾に足し、
    `MainComponent`のコマンドとボタンの両方を同時に足すこと。
*/
enum class EditTool
{
    arrow,    // 選択・移動・伸縮／空いている場所のドラッグで範囲選択
    pencil,   // 描いて作る（アレンジ：MIDIクリップ／ピアノロール：ノート）
    cut,      // クリックした位置で割る
    eraser    // 触れたものを消す（Phase 83/C11）。なぞると通ったぶんだけ消える
};
