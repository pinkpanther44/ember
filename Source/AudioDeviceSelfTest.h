/**
    8.316：**デバイスを付け替えても落ちないこと**を、窓を出さずに確かめる（Phase 309）。

    ```
    "Manta Studio.exe" --audio-selftest
    ```

    ### なぜ機械に数えさせるのか

    本人の報告はこうでした。

    > 「AudioのInputをnoneにするとアプリが落ちる」

    **4回中4回落ちました**（イベントログの番地も全部同じ）。原因は
    JUCEのWASAPI実装のレースで、**止めたあとに音のブロックが1つ通る**もの——
    `GuardedAudioCallback.h`に道筋ごと書いてあります。

    直したかどうかは、**画面を触らないと確かめられませんでした**。
    環境設定を開いて、コンボを選んで、落ちるかどうかを見る。
    **毎回の手作業で、しかも落ちるほうが正解という確認**です。

    ここでやるのは、**同じことをデバイス管理へ直に頼む**ことです。

    | | |
    |---|---|
    | ① | エンジンを起こして、デバイスが開いているか見る |
    | ② | **入力を外す**（`inputDeviceName`を空にする） |
    | ③ | 変更の通知が回りきるまでメッセージを回し、**音も少し流す** |
    | ④ | **生きていること**と、入力が「無い」と答えることを見る |
    | ⑤ | 入力を戻して、また生きていることを見る |

    ### 「落ちなかった」は、どう数えるのか

    **落ちたら数えられません**（プロセスごと消えます）。
    なので**逆を数えます**——最後まで辿り着けたこと自体が答えで、
    落ちていれば`--- N problem(s) ---`の行が**そもそも出ません**。

    終了コードは0が合格です。**落ちた場合は0以外**になり、
    `%APPDATA%/Ember/crash/`に番地が残ります（8.316の`CrashLog`）。

    ### ⚠️ **この道具は、報告された落ち方を再現できていません**

    **正直に書いておきます。** `--without-guard`（＝直す前の姿）で
    **8往復させても落ちませんでした**。本人の手元では**画面から4回中4回**落ちるので、
    **ここで通ることは「直った」の証拠になりません。**

    ```
    "Manta Studio.exe" --audio-selftest --without-guard
    ```

    `GuardedAudioCallback`を素通しにする口は残してあります。
    **いつか落ちるようになったら、そのとき初めて対（つい）になります。**

    **何が足りないのかは、まだ分かっていません。** 画面のほうには
    JUCEの選択UI（コンボの`onChange`・`updateAllControls()`・入力メーター）と、
    読み込み済みのプロジェクトがあります。そのどれかが要るはずです。

    > **だからこの道具は「付け替えても壊れないこと」の見張りに留めてあります。**
    > 直ったかどうかは、**画面で確かめること**（8.316）。
    > **通ったから直った、と読まないこと**——それが同じ穴の作り方です。

    ### 入出力が1つのデバイスの機械では（Linux）

    ALSA（PipeWire）は**入出力が1つ**で、JUCEも入力欄を出しません。
    `inputDeviceName`を空にしても**出力の名前で上書きされる**ので、入力は残ります。

    そこは**数えずに`n/a`と出します**。Windowsの形のまま数えると
    **Linuxで必ず落ちます**——**落ちるべきでないところで落ちる試験は、
    そのうち誰も読まなくなります**（Phase 309で実際に落としました）。

    ### 音のデバイスが無い機械では

    開けなければ**問題0で素通り**します（Linuxのビルド機など）。
    **「試験を通していないのに通ったことになる」のを避けるため**、
    その場合は理由を1行出します。
*/
namespace AudioDeviceSelfTest
{
    /** `--audio-selftest`が含まれていれば走って`true`を返す。 */
    bool runIfRequested (const juce::String& commandLine);
}
