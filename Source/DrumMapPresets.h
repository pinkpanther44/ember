#pragma once

#include <juce_data_structures/juce_data_structures.h>

class DrumMap;

//==============================================================================
/**
    8.284：**ドラムマップのプリセット**（Phase 277／本人の要望。仕様書10.7）。

    本人の言葉：「鍵盤ネームを変更した際、それらの鍵盤ネームプリセットを
    保存・ロードできる仕様を追加することは可能？」

    仕様書10.7が「ユーザー定義マップの管理方法は継続検討」としていたところです
    （`MidiEditModel.h`にもそう書いてあります）。

    ### 何を保存するか

    | | 保存する | なぜ |
    |---|---|---|
    | 音の番号と楽器名 | **する** | これが「鍵盤ネーム」そのもの |
    | チョークグループ | **する** | 楽器名と対で決まるもの（オープン／クローズドHH） |
    | 行のミュート | **しない** | 「いま何を作業しているか」であって、キットの形ではない |

    3つめを入れると、**プリセットを読んだ瞬間に鳴らない行ができます**。
    読み込んだ側からは「プリセットが壊れている」ようにしか見えません。

    ### 読み込みは**上書きだけ、消さない**

    | プリセットに | いまのマップに | どうする |
    |---|---|---|
    | ある | ある | **名前とグループを書き換える** |
    | ある | 無い | **行を足す** |
    | 無い | ある | **そのまま**（消さない） |

    最後の1行が大事です。**行を消すと、その音のノートが画面から消えます**——
    マップに無い音は行を持たないので、`pitchToY()`が画面の外を返します（1.9）。
    打ち込んだノートが「鳴っているのに見えない」状態になるほうが、
    使わない行が残るよりずっと困ります。

    ### 置き場所

    `AppSettings::getDataFolder()/DrumMaps/*.xml`。プロジェクトではなくアプリに紐づくもの
    （どのプロジェクトを開いても同じキットを使いたい）なので、設定と同じ場所です。

    **`StorageLocations`には載せていません。** あちらは「本人が場所を選ぶもの」
    （プロジェクト・録音・バックアップ・テンプレート）で、こちらは
    設定ファイルと同じ**アプリの持ち物**です（`StorageLocations.h`の「移さないもの」の表）。
*/
namespace DrumMapPresets
{
    /** 置き場所。**無ければ作ります。** */
    juce::File getFolder();

    /** 保存してあるプリセットの名前（拡張子なし、アルファベット順）。 */
    juce::StringArray getNames();

    /** いまのマップを、その名前で保存する。**同じ名前があれば上書きします。**

        名前にファイル名として使えない文字があれば落とします
        （落とした結果が空なら保存しません）。 */
    bool save (const DrumMap& map, const juce::String& name);

    /** プリセットをマップへ読み込む。**消さずに上書きと追加だけ**（上の表）。

        `undoManager`を渡せば1回のUndoで戻せます。**区切りは呼び出し側で作ること。** */
    bool load (DrumMap& map, const juce::String& name, juce::UndoManager* undoManager);

    /** 消す。**確認は呼び出し側で。** */
    bool remove (const juce::String& name);
}
