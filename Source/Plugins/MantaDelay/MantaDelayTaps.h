#pragma once

#include <juce_audio_basics/juce_audio_basics.h>

#include <array>

//==============================================================================
/**
    8.214：**マルチタップ**（Phase 243／ディレイ仕様書5-6）。

    ─────────────────────────────────────────────────────────────────────────
    タップの`Time`は、**Timeつまみの何個ぶんか**
    ─────────────────────────────────────────────────────────────────────────

    仕様書5-6は「タップごとの独立Time／Level／Pan」ですが、
    **msで8本ぶん持たせても合わせられません**（設計書4-6の決定でディスプレイは
    ドラッグできないので、数字を8個打ち込むことになります）。

    ここでは**Timeつまみを目盛りの1つぶん**と読み替えて、
    タップは`step`（1〜16）で「何個ぶん後ろか」を持ちます。

    ```
        Time = 1/8 のとき

        step:  1     2     3     4     5     6  …
               ♪     ♪     ♪     ♪     ♪     ♪
               ↑           ↑           ↑
             tap1        tap2        tap3        ← step 1・3・5
    ```

    **Syncの入り切りで意味が変わらない**のが効きます——
    Freeなら「Timeのmsの何倍」、Syncなら「その音価の何個ぶん」。
    どちらでも**同じ`step`が同じリズムを鳴らします。**

    これで仕様書5-6の「リズムパターンプリセット」も**ただの数字の組**になります。

    ─────────────────────────────────────────────────────────────────────────
    上限は8本（仕様書9章の未決定事項）
    ─────────────────────────────────────────────────────────────────────────

    仕様書は「8 or 16など」として決めていません。**8本にしました**（本人の判断）。

    | | |
    |---|---|
    | 増えるパラメータ | 8本なら25個、16本なら49個。**オートメーション一覧が読める長さに収まる** |
    | 鳴らせるリズム | Timeが1/16なら半小節、1/8なら1小節ぶん。**足りないと感じる場面が想像しにくい** |
    | あとで増やせるか | **増やせます。** ただしIDは末尾へ足す決まりなので（9.5）、9〜16番は後ろに並びます |

    ─────────────────────────────────────────────────────────────────────────
    フィードバックは**パターンの終わり**から
    ─────────────────────────────────────────────────────────────────────────

    `getPatternSteps()`が返すのは**生きているタップのいちばん後ろの`step`**です。
    そこから戻すので、**パターンがひとまとまりで繰り返します。**

    最後のタップを動かすと繰り返しの間隔も変わります——
    「**パターンは最後のタップの次から繰り返す**」という、聞いたとおりの動きです。

    ─────────────────────────────────────────────────────────────────────────
    パンは「バランス」型——**真ん中はちょうど1倍**
    ─────────────────────────────────────────────────────────────────────────

    等パワー（`cos`／`sin`）にすると真ん中が0.707倍になり、
    **タップ1本・真ん中・Level 100%がPhase 3と違う音量**になってしまいます。

    `0`は「何もしない」であるべき（8.209）なので、
    **真ん中で1倍、端で片側だけ0**にしました。**どこでも1倍を超えません。**
*/
namespace MantaDelayTaps
{
    /** タップの本数の上限（上の表）。 */
    inline constexpr int maxTaps = 8;

    /** `step`の上限。**Timeつまみ16個ぶん**まで後ろへ置けます。 */
    inline constexpr int maxStep = 16;

    //==========================================================================
    struct Tap
    {
        /** Timeつまみの**何個ぶん後ろか**（1〜`maxStep`）。 */
        int step = 1;

        /** 0〜1。 */
        float level = 1.0f;

        /** -1（左）〜+1（右）。 */
        float pan = 0.0f;
    };

    //==========================================================================
    struct Pattern
    {
        /** 生きているタップの本数（1〜`maxTaps`）。 */
        int count = 1;

        std::array<Tap, (size_t) maxTaps> taps {};

        /** **パターンの長さ**（生きているタップのいちばん後ろの`step`）。

            フィードバックはここから戻します（上の説明）。 */
        int getPatternSteps() const
        {
            const int active = juce::jlimit (1, maxTaps, count);

            int steps = 1;

            for (int i = 0; i < active; ++i)
                steps = juce::jmax (steps, juce::jlimit (1, maxStep, taps[(size_t) i].step));

            return steps;
        }

        /** **Phase 3までと同じ鳴り方か**（＝マルチタップを使っていないか）。

            画面がタップの並びを描くかどうかの判断にも使います——
            **1本しか無いときにパターンの絵を出しても読むものがありません。** */
        bool isSingleTap() const { return juce::jlimit (1, maxTaps, count) == 1; }
    };

    //==========================================================================
    /** バランス型のパン（上の説明）。**真ん中は左右とも1倍。**

        モノラルのときは呼びません（パンの行き先がないため）。 */
    inline void getPanGains (float pan, float& left, float& right)
    {
        const float p = juce::jlimit (-1.0f, 1.0f, pan);

        left  = (p <= 0.0f) ? 1.0f : 1.0f - p;
        right = (p >= 0.0f) ? 1.0f : 1.0f + p;
    }
}
