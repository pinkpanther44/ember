#pragma once

#include <juce_audio_basics/juce_audio_basics.h>

#include <cmath>

//==============================================================================
/**
    8.251：**Saturation**（Phase 260／リバーブ仕様書2-1・5章）。

    仕様書2-1：「オリジナルハードウェアが持っていた**整数演算精度に起因する
    ハードクリップ的な歪み**を再現する機能。LEVパラメータが一定値を超えると作用し、
    グリット感のある響きを付与する。」

    ─────────────────────────────────────────────────────────────────────────
    **つまみは1本**（仕様書のOn/Off＋Thresholdから変えています）
    ─────────────────────────────────────────────────────────────────────────

    仕様書5章は`Saturation（On/Off、Threshold）`と書いていますが、
    **1本のつまみにしました**：

    - `0%`で**何もしません**（＝Off）。ディレイで引いた線の②
    - 上げるほど**掛かり始める高さが下がって**、グリットが増えます

    2つに分けると、**Onなのに閾値が高くて何も起きない**状態が作れます。
    「効かないつまみ」を作らない、という約束（8.208）と同じ話です。

    ─────────────────────────────────────────────────────────────────────────
    形
    ─────────────────────────────────────────────────────────────────────────

    ```
        y = t · tanh(x / t)
    ```

    `t`が閾値です。**小さいところは素通し**（`tanh`の原点の傾きが1）、
    **大きいところは`t`へ寄っていく**——つまり「一定値を超えると作用」。

    8.252：**はじめは別の式でした**（`t + (1−t)·tanh((|x|−t)/(1−t))`）。
    閾値から先を**残りの余白`(1−t)`で割っていた**ので、
    余白が0.99もあってカーブがほぼ直線でした——**つまみを振り切っても
    音が変わりません**でした。割るのは**閾値のほう**です。

    > **`|y| ≤ |x|`です。** 掛けても音は大きくなりません。
    > 深く掛けると小さくはなります——**それが潰すということ**なので、
    > `Level`と`Output`で戻してください。

    ### 置き場所

    仕様書3-2の流れどおり、**`Wet Out`の直前**です（`Level`と`Width`より前）。
    原音には掛かりません——`Mix`で混ぜるのはこの後です。
*/
class MantaReverbSaturation
{
public:
    /** つまみ100%のときの閾値。

        8.252：**0.15から0.01へ下げました**（測って直したところ）。

        はじめは`1.0`から`0.15`まででしたが、**つまみを振り切っても
        何も起きませんでした**——リバーブの出口は`Mix`の前で、
        雑音を入れたときの実効値が**0.11、山でも0.39**しかありません。
        閾値がその上を通り過ぎていたのです。

        > **「効かないつまみ」は、バグと同じです**（8.208）。
        > コードは正しく、閾値も設計どおりに動いていて、**音だけが何も変わらない**。 */
    static constexpr float minThreshold = 0.08f;

    /** ブロックの頭で1回。`amount`は0〜1。 */
    void setAmount (float newAmount)
    {
        const float clamped = juce::jlimit (0.0f, 1.0f, newAmount);

        active = clamped > 0.0001f;

        // 8.252：**指数で配ること**（Phase 260）。
        //
        // 線形に下げると、**下のほうが何も起きない**つまみになります
        // （信号が閾値へ届くまで無反応）。指数なら
        // 25%で0.53、50%で0.28、75%で0.15——**どこを回しても動きます**
        threshold = std::pow (minThreshold, clamped);
        inverseThreshold = 1.0f / juce::jmax (1.0e-4f, threshold);
    }

    bool isActive() const { return active; }

    float processSample (float input) const
    {
        if (! active)
            return input;

        return threshold * std::tanh (input * inverseThreshold);
    }

private:
    float threshold = 1.0f;
    float inverseThreshold = 1.0f;
    bool active = false;
};
